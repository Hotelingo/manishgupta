-- camanishgupta.com content tables, for the shared Supabase project.
--
-- HOW TO USE: copy this file into hotel-finance-book/supabase/migrations/ and
-- apply it from that repo, so one repo owns every migration on the database.
-- Do not run `supabase db push` from the portfolio repo.
--
-- Security model: the portfolio site uses only the publishable (anon) key.
-- Anonymous visitors can SELECT published rows from portfolio_* tables and
-- nothing else. Editing happens in the Supabase dashboard (Table Editor) or a
-- future admin page using the service role, never from the public site.


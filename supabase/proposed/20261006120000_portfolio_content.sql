);

-- ---------------------------------------------------------------------------
-- Row-level security: public read of published rows only
-- ---------------------------------------------------------------------------
do $$
declare
  t text;
begin
  foreach t in array array[
    'portfolio_settings', 'portfolio_record_items', 'portfolio_disciplines', 'portfolio_offers',
    'portfolio_sessions', 'portfolio_projects', 'portfolio_platforms', 'portfolio_courses',
    'portfolio_books', 'portfolio_appearances', 'portfolio_career', 'portfolio_podcast_pages'
  ] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all privileges on public.%I from anon, authenticated', t);
    execute format('grant select on public.%I to anon, authenticated', t);
    execute format('grant all on public.%I to service_role', t);
    execute format('drop policy if exists "Public can read published rows" on public.%I', t);
    if t = 'portfolio_settings' then
      execute format('create policy "Public can read published rows" on public.%I for select to anon, authenticated using (true)', t);
    else
      execute format('create policy "Public can read published rows" on public.%I for select to anon, authenticated using (published)', t);
    end if;
  end loop;
end
$$;

